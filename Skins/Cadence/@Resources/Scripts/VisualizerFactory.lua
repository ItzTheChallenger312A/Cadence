-- VisualizerFactory.lua
-- Dynamically generates MeasureBands.inc, MeasureBandsSmoothed.inc,
-- MeterBars.inc, and MeterShadowBars.inc matching BarCount, MirrorMode,
-- InvertVisualizer, and UseGradientBars. Refreshes once only on changes.

local function clamp(val, lo, hi)
	if val < lo then return lo end
	if val > hi then return hi end
	return val
end

local function writeFile(relPath, content)
	local absPath = relPath:gsub("^#@#", SKIN:GetVariable("@"))
	local f = assert(io.open(absPath, "w"))
	f:write(content)
	f:close()
end

local function buildRawBands(barCount)
	local t = { "; Auto-generated by VisualizerFactory.lua" }
	for i = 0, barCount - 1 do
		t[#t + 1] = string.format(
			"[MeasureAudioRaw%d]\nMeasure=Plugin\nPlugin=AudioLevel\nParent=MeasureAudio\nType=Band\nBandIdx=%d\nChannel=Avg\nGroup=RawAudioMeasures",
			i, i + 1
		)
	end
	return table.concat(t, "\n\n") .. "\n"
end

-- Monstercat neighbor-weighted smoothing with dynamic edge taper at BOTH ends
local function edgeDenom(distFromEdge)
	if distFromEdge == 0 then return 12
	elseif distFromEdge == 1 then return 10
	elseif distFromEdge == 2 then return 8
	elseif distFromEdge == 3 then return 6
	elseif distFromEdge == 4 then return 4
	elseif distFromEdge == 5 then return 3
	elseif distFromEdge <= 8 then return 2.8
	end
	return 3
end

local function buildSmoothedBands(barCount, invert)
	local t = {
		"; Auto-generated by VisualizerFactory.lua",
		"[MeasureAudioMultiplier]\nMeasure=Calc\nFormula=Log(#Multiplier#)\nUpdateDivider=-1",
		"[MeasureAutoMuteController]\nMeasure=Calc\nFormula=#EnableAutoMute#\nIfConditionMode=1\n" ..
		"IfCondition=(#EnableAutoMute# = 1) && (MeasureState <> 1)\n" ..
		"IfTrueAction=[!DisableMeasureGroup RawAudioMeasures]\n" ..
		"IfFalseAction=[!EnableMeasureGroup RawAudioMeasures]\n" ..
		"DynamicVariables=1"
	}
	for i = 0, barCount - 1 do
		local rawIdx = invert == 1 and (barCount - 1 - i) or i
		local leftIdx = clamp(rawIdx - 1, 0, barCount - 1)
		local rightIdx = clamp(rawIdx + 1, 0, barCount - 1)
		local distEdge = math.min(rawIdx, barCount - 1 - rawIdx)
		local denom = edgeDenom(distEdge)

		local expr = string.format(
			"((MeasureAudioRaw%d+MeasureAudioRaw%d+MeasureAudioRaw%d)/%.1f)*MeasureAudioMultiplier",
			leftIdx, rawIdx, rightIdx, denom
		)
		t[#t + 1] = string.format(
			"[MeasureAudioSmoothed%d]\nMeasure=Calc\nAverageSize=#AverageSize#\n" ..
			"Formula=(((#EnableAutoMute# = 1) && (MeasureState <> 1)) ? #MinBarValue# : (#MinBarValue#+%s))\n" ..
			"DynamicVariables=1",
			i, expr
		)
	end
	return table.concat(t, "\n\n") .. "\n"
end

local function parseRgbTuple(str)
	local r, g, b = tostring(str or ""):match("^(%d+)%s*,%s*(%d+)%s*,%s*(%d+)")
	if r then
		return { tonumber(r), tonumber(g), tonumber(b) }
	end
	return nil
end

local function lerpRgb(a, b, t)
	return {
		math.floor(a[1] + (b[1] - a[1]) * t + 0.5),
		math.floor(a[2] + (b[2] - a[2]) * t + 0.5),
		math.floor(a[3] + (b[3] - a[3]) * t + 0.5),
	}
end

local function eval3Stop(c1, c2, c3, t)
	t = clamp(t, 0, 1)
	if t <= 0.5 then
		return lerpRgb(c1, c2, t * 2)
	end
	return lerpRgb(c2, c3, (t - 0.5) * 2)
end

local function fmtRgb(c)
	return string.format("%d,%d,%d", clamp(c[1], 0, 255), clamp(c[2], 0, 255), clamp(c[3], 0, 255))
end

local function buildMeterBars(barCount, mirrorMode, useGradient, barStyle, barWidth, barGap, barHeight, barAngle, dynMode, c1Str, c2Str, c3Str)
	local t = { "; Auto-generated by VisualizerFactory.lua" }
	local anchorExpr = mirrorMode == 1 and "(#BarHeight#*#ScaleVisualizer#/2)" or "(#BarHeight#*#ScaleVisualizer#)"
	local radiusExpr = barStyle == 0 and "(#BarRadius#*#ScaleVisualizer#)" or "0"
	local alphaExpr = barStyle == 2 and "Round(#BarAlpha#*0.72)" or "#BarAlpha#"
	local fillExpr = useGradient == 1 and "Fill LinearGradient BarGrad" or ("Fill Color #ActiveBarColor#," .. alphaExpr)

	local normAngle = (math.floor(barAngle or 90) % 360 + 360) % 360
	local c1 = parseRgbTuple(c1Str)
	local c2 = parseRgbTuple(c2Str)
	local c3 = parseRgbTuple(c3Str)
	local useGlobalSlice = (useGradient == 1 and dynMode == 0 and normAngle ~= 90 and c1 ~= nil and c2 ~= nil and c3 ~= nil)
	local rad = math.rad(normAngle)
	local dx = math.cos(rad)
	local dy = math.sin(rad)
	local totalW = math.max(1, barCount * barWidth + math.max(0, barCount - 1) * barGap)
	local totalH = math.max(1, barHeight)
	local halfSpan = math.max(0.001, (math.abs(totalW * dx) + math.abs(totalH * dy)) * 0.5)

	for i = 0, barCount - 1 do
		local lines = {
			string.format("[MeterBar%d]", i),
			"Meter=Shape",
			"Group=GroupBars | GroupDynamicColors",
			"X=0",
			"Y=0",
			string.format(
				"Shape=Rectangle (%d*(#BarWidth#+#BarGap#)*#ScaleVisualizer#),0,(#BarWidth#*#ScaleVisualizer#),(#BarHeight#*#ScaleVisualizer#),%s | %s | StrokeWidth (#BarStrokeWidth#*#ScaleVisualizer#) | Stroke Color #BarStrokeColor# | Scale 1,(Clamp([MeasureAudioSmoothed%d],#MinBarValue#,1)),0,%s",
				i, radiusExpr, fillExpr, i, anchorExpr
			),
			"TransformationMatrix=[Matrix]",
			"DynamicVariables=1",
		}
		if barStyle == 2 then
			lines[#lines + 1] = "Container=MeterConnectedMask"
		end
		if useGradient == 1 then
			if useGlobalSlice then
				local bx = i * (barWidth + barGap) + barWidth * 0.5
				local tTop = clamp(0.5 + ((bx - totalW * 0.5) * dx + (0 - totalH * 0.5) * dy) / (2 * halfSpan), 0, 1)
				local tBot = clamp(0.5 + ((bx - totalW * 0.5) * dx + (totalH - totalH * 0.5) * dy) / (2 * halfSpan), 0, 1)
				local topRgb = fmtRgb(eval3Stop(c1, c2, c3, tTop))
				local botRgb = fmtRgb(eval3Stop(c1, c2, c3, tBot))
				if (tTop < 0.499 and tBot > 0.501) or (tTop > 0.501 and tBot < 0.499) then
					local relMid = clamp((0.5 - tTop) / (tBot - tTop), 0.01, 0.99)
					lines[#lines + 1] = string.format(
						"BarGrad=90 | %s,%s ; 0.0 | %s,%s ; %.3f | %s,%s ; 1.0",
						topRgb, alphaExpr, fmtRgb(c2), alphaExpr, relMid, botRgb, alphaExpr
					)
				else
					lines[#lines + 1] = string.format(
						"BarGrad=90 | %s,%s ; 0.0 | %s,%s ; 1.0",
						topRgb, alphaExpr, botRgb, alphaExpr
					)
				end
			elseif dy < -0.01 then
				lines[#lines + 1] = string.format(
					"BarGrad=90 | #ActiveColor3#,%s ; 0.0 | #ActiveColor2#,%s ; 0.50 | #ActiveColor1#,%s ; 1.0",
					alphaExpr, alphaExpr, alphaExpr
				)
			else
				lines[#lines + 1] = string.format(
					"BarGrad=90 | #ActiveColor1#,%s ; 0.0 | #ActiveColor2#,%s ; 0.50 | #ActiveColor3#,%s ; 1.0",
					alphaExpr, alphaExpr, alphaExpr
				)
			end
		end
		t[#t + 1] = table.concat(lines, "\n")
	end
	return table.concat(t, "\n\n") .. "\n"
end

local function buildShadowBars(barCount, mirrorMode, barStyle)
	local t = { "; Auto-generated by VisualizerFactory.lua" }
	local anchorExpr = mirrorMode == 1 and "(#BarHeight#*#ScaleVisualizer#/2)" or "(#BarHeight#*#ScaleVisualizer#)"
	local radiusExpr = barStyle == 0 and "(#BarRadius#*#ScaleVisualizer#)" or "0"

	for i = 0, barCount - 1 do
		t[#t + 1] = string.format(
			"[MeterShadowBar%d]\nMeter=Shape\nGroup=GroupShadowBars\nX=0\nY=0\n" ..
			"Shape=Rectangle (%d*(#BarWidth#+#BarGap#)*#ScaleVisualizer#+(3*#ScaleVisualizer#)),(3*#ScaleVisualizer#),(#BarWidth#*#ScaleVisualizer#),(#BarHeight#*#ScaleVisualizer#),%s | Fill Color #DropShadowColor# | StrokeWidth 0 | Scale 1,(Clamp([MeasureAudioSmoothed%d],#MinBarValue#,1)),0,%s\n" ..
			"TransformationMatrix=[Matrix]\nHidden=(((#EnableDropShadow# > 0) && (#VisualizerMode# <> 2)) ? 0 : 1)\nDynamicVariables=1",
			i, i, radiusExpr, i, anchorExpr
		)
	end
	return table.concat(t, "\n\n") .. "\n"
end

function Initialize()
	local barCount = clamp(math.floor(SKIN:ParseFormula(SKIN:GetVariable("BarCount", "64"))), 8, 100)
	local barWidth = SKIN:ParseFormula(SKIN:GetVariable("BarWidth", "5"))
	local barGap = SKIN:ParseFormula(SKIN:GetVariable("BarGap", "8"))
	local barHeight = SKIN:ParseFormula(SKIN:GetVariable("BarHeight", "220"))
	local scaleVis = SKIN:ParseFormula(SKIN:GetVariable("ScaleVisualizer", "1"))
	local mirrorMode = math.floor(SKIN:ParseFormula(SKIN:GetVariable("MirrorMode", "1")))
	local invert = math.floor(SKIN:ParseFormula(SKIN:GetVariable("InvertVisualizer", "0")))
	local useGrad = math.floor(SKIN:ParseFormula(SKIN:GetVariable("UseGradientBars", "1")))
	local barStyle = math.floor(SKIN:ParseFormula(SKIN:GetVariable("BarStyle", "0")))
	local dynMode = math.floor(SKIN:ParseFormula(SKIN:GetVariable("EnableDynamicColors", "0")))
	local barAngle = (math.floor(SKIN:ParseFormula(SKIN:GetVariable("BarGradientAngle", "90"))) % 360 + 360) % 360
	local c1Str = SKIN:GetVariable("Color1", "135,133,254")
	local c2Str = SKIN:GetVariable("Color2", "199,154,224")
	local c3Str = SKIN:GetVariable("Color3", "253,172,199")

	local skinWidth = math.ceil((barCount * (barWidth + barGap) - barGap) * scaleVis)
	local varsPath = SKIN:GetVariable("@") .. "Variables.inc"
	SKIN:Bang("!WriteKeyValue", "Variables", "SkinWidth", tostring(skinWidth), varsPath)

	local colorSig = (dynMode == 0 and barAngle ~= 90)
		and string.format("%s|%s|%s|%d|%d|%d", c1Str, c2Str, c3Str, math.floor(barHeight), math.floor(barWidth), math.floor(barGap))
		or "def"
	local sig = string.format("v3|%d|%d|%d|%d|%d|%d|%d|%s", barCount, mirrorMode, invert, useGrad, barStyle, dynMode, barAngle, colorSig)
	local curSig = SKIN:GetVariable("GeneratedSig", "")

	if sig ~= curSig then
		writeFile("#@#Include\\MeasureBands.inc", buildRawBands(barCount))
		writeFile("#@#Include\\MeasureBandsSmoothed.inc", buildSmoothedBands(barCount, invert))
		writeFile("#@#Include\\MeterBars.inc", buildMeterBars(barCount, mirrorMode, useGrad, barStyle, barWidth, barGap, barHeight, barAngle, dynMode, c1Str, c2Str, c3Str))
		writeFile("#@#Include\\MeterShadowBars.inc", buildShadowBars(barCount, mirrorMode, barStyle))
		SKIN:Bang("!WriteKeyValue", "Variables", "GeneratedSig", sig, varsPath)
		SKIN:Bang("!Refresh")
	end
end
